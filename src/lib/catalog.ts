export type PantryIngredient = {
  name: string;
  emoji: string;
  category: Exclude<(typeof categories)[number], "全部">;
  color: string;
  aliases?: readonly string[];
};
type Seed = readonly [name: string, emoji: string, aliases?: readonly string[]];
function group(
  category: PantryIngredient["category"],
  color: string,
  items: readonly Seed[],
): PantryIngredient[] {
  return items.map(([name, emoji, aliases]) => ({
    name,
    emoji,
    category,
    color,
    aliases,
  }));
}

