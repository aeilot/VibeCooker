export function matchesIngredient(item: PantryIngredient, search: string) {
  const query = search.trim().toLocaleLowerCase();
  if (query && canonicalEnglishIngredient(query) === item.name) return true;
  return [item.name, translate("en", item.name), ...(item.aliases ?? [])].some(
    (name) => name.toLocaleLowerCase().includes(query),
  );
}
export const ingredientEmoji = (name: string) => {
  const canonical = canonicalEnglishIngredient(name) ?? name;
  return (
    (
      pantry.find((p) => p.name === canonical) ??
      pantry.find((p) => canonical.includes(p.name))
    )?.emoji ?? "🌿"
  );
};
